#!/usr/bin/env python3
"""Independent, read-only acceptance probe for invisible Arabic source PDF layers.

This is NOT a source PDF repair or a release approval. It consumes the exact
SHA-pinned published PDF, its existing Pango word map, and a temporary candidate
generated by an independent experimental PR. Checks native search *rectangles*,
selection/copy behaviour, rendered pixels and navigation without modifying any.
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
from hashlib import sha256
import json
import math
from pathlib import Path
import re
import unicodedata

import fitz

AR = re.compile(r"[\u0621-\u064a]+")


def fold(s):
    s = unicodedata.normalize("NFKC", str(s or "")).replace("\u0640", "")
    s = "".join(c for c in s if not unicodedata.combining(c))
    return "".join(AR.findall(s.translate(str.maketrans("أإآٱؤئىة", "ااااوييه"))))


def rect_values(rect):
    return [round(float(v), 4) for v in rect]


def center_gap(a, b):
    x, y = (a.x0 + a.x1) / 2, (a.y0 + a.y1) / 2
    u, v = (b.x0 + b.x1) / 2, (b.y0 + b.y1) / 2
    return math.hypot(x-u, y-v)


def iou(a, b):
    c = a & b
    if c.is_empty:
        return 0.0
    area = max(0.0, c.width) * max(0.0, c.height)
    denom = max(0.0, a.width*a.height) + max(0.0, b.width*b.height) - area
    return area / denom if denom else 0.0


def links_fingerprint(page):
    # Ignore incidental object xref or PDF serialization: compare exact meaning.
    result = []
    for link in page.get_links():
        rect = fitz.Rect(link["from"])
        target = link.get("to")
        if hasattr(target, "x") and hasattr(target, "y"):
            target = [float(target.x), float(target.y)]
        else:
            target = str(target)
        result.append({
            "kind": link.get("kind"), "dest_page": link.get("page"),
            "uri": link.get("uri", ""), "nameddest": link.get("nameddest", ""),
            "from": rect_values(rect), "target": target,
        })
    return result


def link_semantics(a, b, tolerance=0.012):
    # Bijectively match links within each semantic group, checking source and
    # destination geometry numerically. This excludes xref IDs by design.
    x, y = links_fingerprint(a), links_fingerprint(b)
    if len(x) != len(y):
        return False, {"baseline": len(x), "candidate": len(y), "reason": "different counts"}
    def key(v):
        return (v["kind"], v["dest_page"], v["uri"], v["nameddest"])
    pool = defaultdict(list)
    for v in y:
        pool[key(v)].append(v)
    bad = []
    for v in x:
        group = pool[key(v)]
        found = None
        for i, dest in enumerate(group):
            if max(abs(p-q) for p, q in zip(v["from"], dest["from"])) > tolerance:
                continue
            va, vb = v["target"], dest["target"]
            if isinstance(va, list) and isinstance(vb, list):
                if max(abs(p-q) for p, q in zip(va, vb)) > tolerance:
                    continue
            elif va != vb:
                continue
            found = i
            break
        if found is None:
            if len(bad) < 5:
                bad.append(v)
        else:
            group.pop(found)
    return not bad and not any(pool.values()), {
        "baseline": len(x), "candidate": len(y),
        "unmatched_baseline_samples": bad,
        "unmatched_candidate_count": sum(len(z) for z in pool.values()),
    }


def source_rows(m):
    for key, words in sorted(
        m["segments"].items(),
        key=lambda kv: tuple(int(x) if x.isdigit() else x for x in kv[0].split(":"))
    ):
        if not key.endswith((":ar", ":vocalized")):
            continue
        yield key, words


def sample_targets(m):
    counts = Counter()
    for _, words in source_rows(m):
        for word, page, *_ in words:
            counts[(int(page), fold(word))] += 1
    singles, pairs = [], []
    total_rows = 0
    for key, words in source_rows(m):
        total_rows += 1
        eligible = [x for x in words if len(fold(x[0])) >= 3]
        choice = next((x for x in eligible if len(fold(x[0])) >= 5
                       and counts[(int(x[1]), fold(x[0]))] == 1), None)
        choice = choice or next((x for x in eligible
                                 if counts[(int(x[1]), fold(x[0]))] == 1), None)
        if choice is None and eligible:
            choice = eligible[0]
        if choice is not None:
            singles.append({
                "segment": key, "word": choice[0], "page": int(choice[1]),
                "expected": list(choice[2:6]),
                "unique_on_page": counts[(int(choice[1]), fold(choice[0]))] == 1,
            })
        firstpage = int(words[0][1])
        firstwords = [w for w in words if int(w[1]) == firstpage]
        if len(firstwords) >= 2:
            # Pango-map order is the source's original authorial word order.
            chosen = firstwords[:2]
            pairs.append({"segment": key, "words": [w[0] for w in chosen],
                          "page": firstpage,
                          "expected": [list(w[2:6]) for w in chosen]})
    return singles, pairs, total_rows


def inspect(source, candidate, mapping, max_examples=25):
    manifest = json.loads(Path(mapping).read_text(encoding="utf-8"))
    actual_sha = sha256(Path(source).read_bytes()).hexdigest()
    if manifest["source_sha256"] != actual_sha:
        raise ValueError("Refusing unverified source-map SHA mismatch")
    singles, pairs, mapped_segments = sample_targets(manifest)
    report = {
        "experimental": True, "release_approved": False,
        "original_sha256": actual_sha,
        "prototype_sha256": sha256(Path(candidate).read_bytes()).hexdigest(),
        "source_segments": mapped_segments,
        "single_word_queries": len(singles),
        "two_word_queries": len(pairs),
    }
    with fitz.open(source) as original, fitz.open(candidate) as repaired:
        if len(original) != len(repaired):
            raise ValueError("Candidate page count differs from original")
        pages_with_visual_changes, link_problems = [], []
        for i in range(len(original)):
            if original[i].get_pixmap(alpha=False).samples != repaired[i].get_pixmap(alpha=False).samples:
                pages_with_visual_changes.append(i+1)
            ok, detail = link_semantics(original[i], repaired[i])
            if not ok:
                link_problems.append({"page": i+1, **detail})
        names_a, names_b = original.resolve_names(), repaired.resolve_names()
        anchor_mismatches = []
        for n in range(1, 259):
            k = f"section-{n}"
            a, b = names_a.get(k), names_b.get(k)
            if not a or not b or a.get("page") != b.get("page"):
                anchor_mismatches.append(k)
            elif a.get("to") is not None and b.get("to") is not None:
                if center_gap(fitz.Rect(*list(a["to"])*2), fitz.Rect(*list(b["to"])*2)) > 0.012:
                    anchor_mismatches.append(k)
        report["document_integrity"] = {
            "page_count": len(original), "pixel_changed_pages": pages_with_visual_changes,
            "semantic_link_mismatches": link_problems[:30],
            "section_anchor_mismatches": anchor_mismatches,
            "source_outline_equal": original.get_toc() == repaired.get_toc(),
        }
        bypage = {}
        def p_context(n):
            if n not in bypage:
                page = repaired[n-1]
                bypage[n] = (page, page.get_textpage())
            return bypage[n]

        # Use native MuPDF search API; match each returned annotation rectangle to
        # its exact Pango source-word rectangle instead of merely checking the
        # query's occurrence somewhere on that page.
        single_results, geom_examples, copy_examples = [], [], []
        for target in singles:
            n = target["page"]
            page, textpage = p_context(n)
            needle = target["word"]
            expected = fitz.Rect(target["expected"])
            if not len(fold(needle)):
                continue
            hits = page.search_for(needle, textpage=textpage)
            nearest = (max(hits, key=lambda h: iou(fitz.Rect(h), expected))
                       if hits else None)
            overlap = iou(fitz.Rect(nearest), expected) if nearest else 0.0
            delta = center_gap(fitz.Rect(nearest), expected) if nearest else None
            passed = bool(nearest is not None and overlap >= 0.55)
            row = {
                "segment": target["segment"], "page": n, "word": needle,
                "unique_on_page": target["unique_on_page"], "native_found": bool(hits),
                "native_hits_page": len(hits), "alignment_pass": passed,
                "best_iou": round(overlap, 4),
                "center_delta_pt": round(delta, 3) if delta is not None else None,
            }
            single_results.append(row)
            if not passed and len(geom_examples) < max_examples:
                geom_examples.append({
                    **row, "expected": rect_values(expected),
                    "native_rect": rect_values(nearest) if nearest else None,
                })
            if target["unique_on_page"] and len(copy_examples) < 18:
                rect = fitz.Rect(expected.x0-2, expected.y0-2, expected.x1+2, expected.y1+2)
                a_text = original[n-1].get_textbox(rect)
                b_text = repaired[n-1].get_textbox(rect)
                copy_examples.append({
                    "segment": target["segment"], "word": needle,
                    "baseline_contains_word": fold(needle) in fold(a_text),
                    "candidate_contains_word": fold(needle) in fold(b_text),
                    "baseline_text": a_text[:160], "candidate_text": b_text[:160],
                })

        pair_results, pair_examples = [], []
        for target in pairs:
            n = target["page"]
            page, textpage = p_context(n)
            phrase = " ".join(target["words"])
            hits = page.search_for(phrase, textpage=textpage)
            expected = fitz.Rect(target["expected"][0])
            expected.include_rect(fitz.Rect(target["expected"][1]))
            overlap = max([iou(fitz.Rect(h), expected) for h in hits] or [0])
            pair_results.append({
                "segment": target["segment"], "page": n, "phrase": phrase,
                "native_found": bool(hits), "best_iou": round(overlap, 4),
            })
            if not hits and len(pair_examples) < max_examples:
                pair_examples.append({"segment": target["segment"], "page": n,
                                      "phrase": phrase})
        unique_rows = [r for r in single_results if r["unique_on_page"]]
        report["single_word"] = {
            "native_hit_count": sum(r["native_found"] for r in single_results),
            "aligned_count_iou_ge_0_55": sum(r["alignment_pass"] for r in single_results),
            "unique_word_targets": len(unique_rows),
            "unique_native_hit_count": sum(r["native_found"] for r in unique_rows),
            "unique_aligned_count": sum(r["alignment_pass"] for r in unique_rows),
            "hit_iou_min": min((r["best_iou"] for r in single_results if r["native_found"]), default=None),
            "hit_iou_median": sorted([r["best_iou"] for r in single_results if r["native_found"]])[sum(r["native_found"] for r in single_results)//2] if any(r["native_found"] for r in single_results) else None,
            "problem_samples": geom_examples,
        }
        report["two_word"] = {
            "native_hit_count": sum(r["native_found"] for r in pair_results),
            "query_count": len(pair_results),
            "query_failed_samples": pair_examples,
        }
        report["copy_region_samples"] = copy_examples
        report["interpretation_limits"] = [
            "Search rectangles measured by PyMuPDF only: must repeat in native PDFKit, PDFium, PDF.js and Acrobat.",
            "A single-word hit can represent another identical word on the same page; unique-on-page results are separately reported.",
            "The baseline PDF's garbled source text is still present beneath the invisible layer; copying may include two text objects.",
            "The test makes no changes to the candidate, source, Pango maps, print generator, publication assets or personal notes.",
        ]
    return report


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--source",type=Path,required=True)
    p.add_argument("--candidate",type=Path,required=True)
    p.add_argument("--map",type=Path,required=True)
    p.add_argument("--output",type=Path,required=True)
    args=p.parse_args()
    result=inspect(args.source,args.candidate,args.map)
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(json.dumps(result,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    print("OVERLAY_SELECTION_QA",json.dumps({
        "segments": result["source_segments"],
        "single_query_count": result["single_word_queries"],
        "single_found": result["single_word"]["native_hit_count"],
        "unique_found": result["single_word"]["unique_native_hit_count"],
        "unique_aligned": result["single_word"]["unique_aligned_count"],
        "pair_found": result["two_word"]["native_hit_count"],
        "pair_total": result["two_word"]["query_count"],
        "pixel_changed_pages": len(result["document_integrity"]["pixel_changed_pages"]),
        "link_mismatches": len(result["document_integrity"]["semantic_link_mismatches"]),
        "anchor_mismatches": len(result["document_integrity"]["section_anchor_mismatches"]),
    },ensure_ascii=False),flush=True)
    print("RESULT_NOT_A_RELEASE_CERTIFICATE",args.output,flush=True)


if __name__=="__main__":
    main()
