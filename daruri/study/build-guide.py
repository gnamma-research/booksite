#!/usr/bin/env python3
"""Build the browser data and equivalent no-JavaScript guide from lesson JSON.

Run from any directory: python daruri/study/build-guide.py
The PDF companion uses the same lesson files; see build-guide-pdf.py.
"""
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEVELS = [('basic', 'Basic — Foundations'), ('intermediate', 'Intermediate — Close Reading'), ('advanced', 'Advanced — Research')]
UNITS = ['Purpose and method', 'Rulings and responsibility', 'Reports and transmission', 'Abrogation, consensus and presumption', 'Language and interpretation', 'Qiyās and legal extension', 'Prophetic action', 'Juristic judgement and authority']
START = '<!-- STUDY GUIDE GENERATED START -->'
END = '<!-- STUDY GUIDE GENERATED END -->'
e = lambda value: html.escape(str(value), quote=True)


def load_book():
    # Match the current reader asset, not a historical snapshot.
    import re
    source = (ROOT / 'index.html').read_text()
    filename = re.search(r'<script src="(edition[^"?]+\.js)(?:\?[^"]*)?"', source).group(1)
    encoded = (ROOT / filename).read_text().split('.textContent=', 1)[1].strip().rstrip(';')
    return json.loads(json.loads(encoded))


def paragraph(text):
    return '<p>' + e(text) + '</p>'


def listing(values, ordered=False):
    tag = 'ol' if ordered else 'ul'
    return '<' + tag + '>' + ''.join('<li>' + e(v) + '</li>' for v in values) + '</' + tag + '>'


def build():
    lessons = []
    for file in sorted((ROOT / 'study').glob('lessons-*.json')):
        lessons.extend(json.loads(file.read_text()))
    lessons.sort(key=lambda x: x['number'])
    assert [x['number'] for x in lessons] == list(range(1, 29)), 'Need all 28 questions exactly once'
    assert len({x['id'] for x in lessons}) == 28, 'Duplicate lesson IDs'
    book = load_book()
    sections = {str(s['id']): s for s in book['sections']}
    apps = {a['id']: a for a in book['apps']}
    for lesson in lessons:
        assert set(lesson['levels']) == {x[0] for x in LEVELS}
        assert 1 <= lesson['unit'] <= 8
        assert all(a in apps for a in lesson['applications'])
        for key, _ in LEVELS:
            level = lesson['levels'][key]
            assert level['objective'] and level['explanation'] and level['example']['text']
            assert level['sections'] and all(str(n) in sections for n in level['sections'])
            assert len(set(level['sections'])) == len(level['sections'])
            assert len(level['tasks']) == len(level['feedback']) >= 2
    data = {'version': '20261020-study1', 'units': UNITS, 'lessons': lessons}
    (ROOT / 'study-guide-data.js').write_text('/* Generated by study/build-guide.py; edit study/lessons-*.json. */\nwindow.DARURI_STUDY_DATA = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')

    out = ['<section class="fb-page fb-reference-page sg-fallback" id="study">',
           '<header><p class="sg-eyebrow">AL-ḌARŪRĪ · STUDY GUIDE</p><h1>One text. Three depths of study.</h1>',
           '<p>All 28 questions are available at Basic (Foundations), Intermediate (Close Reading) and Advanced (Research). Open a question’s level to see its explanation, ordered readings, task and feedback. Start with Basic if legal theory is new to you.</p>',
           '<p>These are editorial teaching lessons, not chapters named by Ibn Rushd. Source section numbers remain stable; the numbered text is distinct from explanations and proposed research tasks.</p>',
           '<a href="daruri-study-guide.pdf?v=20261020-study1">Download the complete three-level study guide (PDF)</a></header>',
           '<span id="study?level=basic"></span><span id="study?level=intermediate"></span><span id="study?level=advanced"></span><nav aria-label="Study questions"><ol>']
    out += ['<li><a href="#study-' + e(l['id']) + '">' + e(l['title']) + '</a></li>' for l in lessons]
    out.append('</ol></nav>')
    for lesson in lessons:
        out.append('<article class="sg-fallback-question" id="study-' + e(lesson['id']) + '"><p class="sg-eyebrow">Unit ' + str(lesson['unit']) + ' · ' + e(UNITS[lesson['unit'] - 1]) + '</p><h2>Question ' + str(lesson['number']) + '. ' + e(lesson['title']) + '</h2>' + paragraph(lesson['summary']))
        out.append('<details><summary>Before you begin</summary>' + listing(lesson['prerequisites']) + '</details><details class="sg-terms"><summary>Key terms</summary><dl>')
        out += ['<dt>' + e(t['term']) + '</dt><dd>' + e(t['definition']) + '</dd>' for t in lesson['terms']]
        out.append('</dl></details>')
        for key, label in LEVELS:
            level = lesson['levels'][key]
            out.append('<details class="sg-fallback-level" id="study-' + e(lesson['id']) + '-' + key + '"><summary id="study?topic=' + e(lesson['id']) + '&amp;level=' + key + '">' + e(label) + '</summary><h3>What you will learn</h3>' + paragraph(level['objective']) + '<h3>1. Understand the question</h3>')
            out += [paragraph(x) for x in level['explanation']]
            out.append('<aside class="sg-example"><h4>' + e(level['example']['title']) + '</h4>' + paragraph(level['example']['text']) + '</aside><h3>2. Read the assigned passages</h3><ol>')
            for n in level['sections']:
                s = sections[str(n)]
                out.append('<li><a href="#section=' + str(n) + '">§' + str(n) + ' · ' + e(s['title']) + '</a><small> · al-ʿAlawī (1994), printed pages ' + e(', '.join(map(str, s['pages']))) + '</small></li>')
            out.append('</ol><h3>3. ' + ('Develop an argument' if key == 'advanced' else 'Try it yourself') + '</h3><p>Write your answer before opening the feedback. Support it with the numbered passages.</p>' + listing(level['tasks'], True) + '<details class="sg-feedback"><summary>' + ('Research criteria and guidance' if key == 'advanced' else 'Reasoned feedback') + '</summary>' + listing(level['feedback'], True) + '</details></details>')
        if lesson['applications']:
            out.append('<details><summary>Related cases in the Bidāya</summary><p>Editorial comparisons: check the cited case before treating it as evidence for al-Ḍarūrī.</p>')
            for app_id in lesson['applications']:
                a = apps[app_id]
                out.append('<h3>' + e(app_id + ' · ' + a['title']) + '</h3>' + paragraph(a.get('relation', 'Editorial parallel')) + paragraph(a['text']) + paragraph(a['locator']) + '<a href="' + e(a['url']) + '">Read the cited Arabic source</a>')
            out.append('</details>')
        out.append('<a href="#study">Back to all questions</a></article>')
    out.append('<footer class="sg-editorial"><p>Use the reader section number and the named edition’s printed page when citing. PDF physical pages are separately labelled in the enhanced reader. Advanced comparisons are research assignments; their feedback gives criteria, not a claim that every proposed source has already been compared.</p></footer></section>')
    generated = START + '\n' + '\n'.join(out) + '\n' + END
    file = ROOT / 'index.html'
    source = file.read_text()
    if START in source:
        a, b = source.index(START), source.index(END) + len(END)
    else:
        a = source.index('<section class="fb-page fb-reference-page" id="study">')
        b = source.index('</section>', a) + len('</section>')
    file.write_text(source[:a] + generated + source[b:])
    print('Built 28 questions, 84 levels, browser data and equivalent no-JavaScript guide.')


if __name__ == '__main__':
    build()
